-- TREASURE HUNTER DATABASE
-- این فایل را کامل داخل Supabase -> SQL Editor اجرا کن.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  email text,
  coins bigint not null default 0,
  distance_m double precision not null default 0,
  treasures_count integer not null default 0,
  total_earned bigint not null default 0,
  theme text not null default 'dark',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.game_state (
  user_id uuid primary key references auth.users(id) on delete cascade,
  center_lat double precision not null,
  center_lon double precision not null,
  cashout_radius_m double precision not null default 250,
  seed bigint not null,
  treasures_found integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.treasures (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  sequence integer not null,
  latitude double precision not null,
  longitude double precision not null,
  radius_m double precision not null default 38,
  reward integer not null default 50,
  found boolean not null default false,
  found_at timestamptz,
  created_at timestamptz not null default now(),
  unique(user_id,sequence)
);

create index if not exists treasures_user_idx
on public.treasures(user_id,found,sequence);

alter table public.profiles enable row level security;
alter table public.game_state enable row level security;
alter table public.treasures enable row level security;

